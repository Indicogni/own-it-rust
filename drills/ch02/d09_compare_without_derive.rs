struct Point {
    x: i32,
    y: i32,
}

fn main() {
    let a = Point { x: 1, y: 2 };
    let b = Point { x: 1, y: 2 };
    assert!(a == b); // KEEP
    assert_eq!(a.x + b.y, 3); // KEEP
}
